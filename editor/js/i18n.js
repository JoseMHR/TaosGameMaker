/**
 * Traduce una clave de interfaz según el idioma activo en el store (o fallback a 'en' / 'es').
 */
export function t(key, subs = {}, lang = null) {
	const currentLang = lang || (window.__EDITOR_STORE__ ? window.__EDITOR_STORE__.currentLang : 'es') || 'es';
	const langTable = UI_TRANSLATIONS[currentLang] || UI_TRANSLATIONS.en || UI_TRANSLATIONS.es;
	let text = langTable[key] || UI_TRANSLATIONS.en?.[key] || UI_TRANSLATIONS.es?.[key] || key;

	for (const k in subs) {
		text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), subs[k]);
	}
	return text;
}
